import saleStatus from '~/utils/saleStatus'
import { checkImageExisted } from '~/utils/utils'
// import ProjectDetailsSlider from "../../components/ProjectDetailsSlider.vue";
export default {
  head() {
    return {
      title: 'Projects | Landing Realty | A Toronto Real Estate Company',
    }
  },
  data() {
    return {
      detailDividerStyle:
        'height: 40px; background-color: #0b2c42; margin: auto',
      featuresDividerStyle:
        'height: 100%; background-color: #d9d9d9; margin: auto',
      amenitiesDividerStyle:
        'height: 90%; background-color: #white; margin: auto',
      saleStatus,
      registrationForm: this.$form.createForm(this),
    }
  },
  async asyncData({ $axios, route }) {
    const res = await $axios.$get(`/assignments/${route.params.slug}`, {
      params: {
        populate: '*',
      },
    })
    console.log(res)
    return {
      item: res.data,
      recommended: undefined,
      floorPlanModal: false,
      fromSearch: false,
    }
  },
  created() {
    if (this.$store.state.fromSearchResult) {
      this.fromSearch = true
      this.$store.commit('setFromSearchResult', false)
    }
    this.$axios
      .$get('/assignments', {
        params: {
          filters: {
            id: {
              $ne: this.item.id,
            },
            type: {
              $eq: this.item.attributes.type,
            },
            style: {
              $eq: this.item.attributes.style,
            },
          },
          populate: ['images'],
          pagination: {
            pageSize: 4,
          },
        },
      })
      .then((res) => {
        this.recommended = res.data
      })
  },
  methods: {
    decimalFormatter(price) {
      price = price.toString().replace(/\B(?=(\d{3})+(?!\d))/g, ',')
      return price
    },
    breadcrumbRoute(category) {
      let route = ''
      if (category === 'resell') {
        route = '/projects/resales'
      } else if (category === 'precon') {
        route = '/projects/pre-construction'
      } else if (category === 'assignment') {
        route = '/projects/assignment'
      } else if (category === 'rental') {
        route = '/projects/rental'
      } else {
        route = '/projects/commercial'
      }
      return route
    },
    // checkImageExisted(img){
    //   if(!img.data){
    //     return '/img/about/about-img.jpg'
    //   }else{
    //     return img.data[0].attributes.url
    //   }
    // },
    submitForm(e) {
      e.preventDefault()
      this.registrationForm.validateFields(async (err, values) => {
        if (!err) {
          // const fd = new FormData()
          this.$axios.$post('/precon-forms', {data: {
            first_name: values.firstName,
            last_name: values.lastName,
            phone: values.phone,
            email: values.email,
            realtor:values.realtor,
            message: values.message,
          }}).then(
            res => {
              if (res) {
                this.$message.success('Application received! We\'ll get back to you as soon as possible!')
                this.registrationForm = this.$form.createForm(this)
              } else {
                this.$message.success('Uh oh! Your application wasn\'t sent. Please try again.')
              }
            }
          )
        }
      })
    },
  },
}
</script>

